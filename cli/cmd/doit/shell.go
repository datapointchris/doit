// shells are the shells doit prints a gate and a completion for.
var shells = []string{"zsh"}

func newShellCommand() *cobra.Command {
	cmd := goclikit.AsNamespace(&cobra.Command{
		Use:   "shell",
		Short: "What your shell loads from doit: a reminder of due review items, and completion",
		Long: "What your shell loads from doit: a reminder of due review items, and completion.\n\n" +
			"Each prints a script for your rc, and no shell waits on the service. The reminder\n" +
			"starts `doit review nudge` in the background, and a Tab reads the pursuit names that\n" +
			"the last `doit next` or `doit pursuits list` left on this desk.",
		Example: "  eval \"$(doit shell init zsh)\"        in your rc: a reminder of due review items\n" +
			"  eval \"$(doit shell completion zsh)\"  in your rc: completion for the verbs and your pursuit names",
		GroupID:     thisMachine,
		Annotations: map[string]string{startsNoUpdateCheck: ""},
	})
	cmd.AddCommand(newShellInitCommand(), newShellCompletionCommand())
	return cmd
}

func newShellInitCommand() *cobra.Command {
	return &cobra.Command{
		Use:   "init <shell>",
		Short: "Print the startup block that nudges you about due items",
		Long: "Print the startup block that nudges you about due items.\n\n" +
			"Add `eval \"$(doit shell init zsh)\"` to your rc. It prints, so gate it on whatever\n" +
			"switch decides you want reminders in this shell.",
		Example:   "  doit shell init zsh  print the block, for `eval \"$(doit shell init zsh)\"` in your rc",
		Args:      oneShell("init"),
		ValidArgs: shells,
		RunE: func(cmd *cobra.Command, _ []string) error {
			_, err := io.WriteString(cmd.OutOrStdout(), zshStartupGate())
			return err
		},
	}
}

func newShellCompletionCommand() *cobra.Command {
	return &cobra.Command{
		Use:   "completion <shell>",
		Short: "Print the completion script for the verbs and your pursuit names",
		Long: "Print the completion script for the verbs and your pursuit names.\n\n" +
			"Each Tab runs `doit __complete`, which answers from this binary's commands and from\n" +
			"the names file on this desk, and asks no service. The script's first line is its\n" +
			"#compdef tag, so it can be sourced or autoloaded from your fpath as `_doit`.",
		Example:   "  doit shell completion zsh  print the script, for `eval \"$(doit shell completion zsh)\"` in your rc",
		Args:      oneShell("completion"),
		ValidArgs: shells,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return cmd.Root().GenZshCompletion(cmd.OutOrStdout())
		},
	}
}

// oneShell takes exactly one argument naming a shell in shells, and refuses any
// other as a usage mistake naming the ones there are.
func oneShell(kind string) cobra.PositionalArgs {
	return func(_ *cobra.Command, args []string) error {
		if len(args) != 1 {
			return goclikit.UsageError(fmt.Errorf("name the shell to print the %s for: %s", kind, strings.Join(shells, ", ")))
		}
		for _, shell := range shells {
			if args[0] == shell {
				return nil
			}
		}
		return goclikit.UsageError(fmt.Errorf("no %s for %s; doit generates: %s", kind, args[0], strings.Join(shells, ", ")))
	}
}

// zshStartupGate is the startup nudge gate, which no shell waits on.
//
// The nudge asks the service, so the gate starts it in the background and the
// next shell prints what it found, once. A marker's mtime bounds that to once
// per interval on each desk, so a shell between intervals costs a few file
// tests. The service holds when the nudge last showed anywhere, so the schedule
// is one rolling one across every desk. A nudge that fails is shown the same
// way, because a broken nudge that stays quiet reads as a clear register.
func zshStartupGate() string {
	showing := deskfiles.NudgeShowingPath()
	marker := deskfiles.NudgeMarkerPath()
	waiting := showing + ".next"
	lines := []string{
		"# doit — surface the review register's due items once per interval. The check",
		"# runs in the background, and the next shell prints what it found.",
		"# Generated by `doit shell init zsh`; edit it there, not here.",
		"if (( $+commands[doit] )); then",
		`  if [[ -s "` + showing + `" ]]; then`,
		`    cat "` + showing + `"`,
		`    rm -f "` + showing + `"`,
		"  fi",
		`  _doit_mins="$(cat "` + deskfiles.NudgeIntervalPath() + `" 2>/dev/null || echo ` + strconv.Itoa(deskfiles.DefaultNudgeMinutes) + `)"`,
		`  if [[ ! -f "` + marker + `" || -n "$(find "` + marker + `" -mmin +"$_doit_mins" 2>/dev/null)" ]]; then`,
		`    mkdir -p "` + deskfiles.CacheDir() + `"`,
		`    : >| "` + marker + `"`,
		"    (",
		`      COLUMNS=$COLUMNS FORCE_COLOR=1 doit review nudge >| "` + waiting + `" 2>&1`,
		`      if [[ -s "` + waiting + `" ]]; then mv -f "` + waiting + `" "` + showing + `"; else rm -f "` + waiting + `"; fi`,
		"    ) >/dev/null 2>&1 &!",
		"  fi",
		"  unset _doit_mins",
		"fi",
		"",
	}
	return strings.Join(lines, "\n") + "\n"
}
