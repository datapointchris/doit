"""What the shell needs from doit, emitted by doit.

dotfiles carries one `eval` line per block, and doit carries the block. Each block
names doit's internals: the cache files the nudge gate and the completion read,
and the verb list. A block kept in a config repo would carry
those details away from the code that owns them, and break whenever one moved.
Kept here, a changed path or verb changes in one place, and every machine picks it
up on its next shell rather than on the next dotfiles edit.

The completion reads a flat file rather than calling doit. Completion has to feel
instant and starting a Python process does not, so every run of the draw leaves
`next-names.txt` behind for the shell to read with no subprocess at all. That is
also why this is a generated script rather than typer's `--install-completion`:
typer's completion spawns the program on every TAB.

The nudge and the completion are separate blocks because they load at different
points and answer to different switches: the nudge prints and is gated on wanting reminders, and the
completion is silent and unconditional. Folding them together would put a
completion behind a toggle that has nothing to do with it.
"""

from typing import Annotated

import typer

from doit import pursuits
from doit import review
from doit.render import examples
from doit.service_commands import review as review_commands

app = typer.Typer(
    name='shell',
    no_args_is_help=True,
    help='What your shell loads from doit: a reminder of due review items, and completion.',
    epilog=examples(
        ('eval "$(doit shell init zsh)"', 'in your rc: a reminder of due review items'),
        ('eval "$(doit shell completion zsh)"', 'in your rc: completion for the verbs and your pursuit names'),
    ),
)

SHELLS = ('zsh',)


def zsh_init() -> str:
    """The startup nudge gate, which no shell waits on.

    The nudge asks the service, so the gate starts it in the background and the
    next shell prints what it found, once. A marker's mtime bounds that to once
    per interval on each machine, so a shell between intervals costs a few file
    tests. The service holds when the nudge last showed anywhere, so the schedule
    is one rolling one across every machine. A nudge that fails is shown the same
    way, because a broken nudge that stays quiet reads as a clear register.
    """
    showing, waiting = review_commands.NUDGE_SHOWING, f'{review_commands.NUDGE_SHOWING}.next'
    return f"""\
# doit — surface the review register's due items once per interval. The check
# runs in the background, and the next shell prints what it found.
# Generated by `doit shell init zsh`; edit it there, not here.
if (( $+commands[doit] )); then
  if [[ -s "{showing}" ]]; then
    cat "{showing}"
    rm -f "{showing}"
  fi
  _doit_mins="$(cat "{review_commands.NUDGE_INTERVAL}" 2>/dev/null || echo {review.DEFAULT_NUDGE_MINUTES})"
  if [[ ! -f "{review_commands.NUDGE_MARKER}" || -n "$(find "{review_commands.NUDGE_MARKER}" -mmin +"$_doit_mins" 2>/dev/null)" ]]; then
    mkdir -p "{review_commands.NUDGE_MARKER.parent}"
    : >| "{review_commands.NUDGE_MARKER}"
    (
      COLUMNS=$COLUMNS FORCE_COLOR=1 doit review nudge >| "{waiting}" 2>&1
      if [[ -s "{waiting}" ]]; then mv -f "{waiting}" "{showing}"; else rm -f "{waiting}"; fi
    ) >/dev/null 2>&1 &!
  fi
  unset _doit_mins
fi
"""


def zsh_completion() -> str:
    """Completion for the verbs, and for pursuit names from the cache."""
    return f"""\
#compdef doit
# Generated by `doit shell completion zsh`; edit it there, not here.

_doit_pursuits() {{
  local cache="{pursuits.NAMES_CACHE}"
  [[ -r $cache ]] || return 1
  local -a pursuits
  # name<TAB>description in the file, name:description for _describe.
  pursuits=("${{(@f)$(<$cache)}}")
  pursuits=("${{(@)pursuits//$'\\t'/:}}")
  _describe -t pursuits 'pursuit' pursuits
}}

_doit() {{
  local -a verbs
  verbs=(
    'next:What to do now, drawn from your weighted pursuits'
    'dashboard:Everything outstanding across your apps, in lanes'
    'today:What today still wants, and what it has had'
    'happened:What every record says happened over a window'
    'forecast:What the register would have you do, run forward'
    'pursuits:The weights the draw runs on'
    'review:What is due to revisit or practice'
    'sources:Which apps doit asks for lanes'
    'shell:What your shell loads from doit'
    'auth:Log this machine in to the doit service'
    'config:Where this machine points doit, and the files it keeps'
    'update:Update doit to the latest release'
  )

  if (( CURRENT == 2 )); then
    _describe -t verbs 'doit command' verbs
    return
  fi

  # `pursuits log` and `pursuits skip` both take a pursuit, and they are the two you type most.
  case "$words[2] $words[3]" in
    'pursuits log'|'pursuits skip') (( CURRENT == 4 )) && _doit_pursuits ;;
  esac
}}

compdef _doit doit
"""


GENERATORS = {
    'zsh': {'init': zsh_init, 'completion': zsh_completion},
}


def emit(shell: str, kind: str) -> int:
    if shell not in GENERATORS:
        raise typer.BadParameter(f'no {kind} for {shell}; doit generates: {", ".join(SHELLS)}')
    # Plain print: this is a script another process evals, not a message.
    print(GENERATORS[shell][kind]())
    return 0


ShellArgument = Annotated[str, typer.Argument(help=f'Which shell: {", ".join(SHELLS)}.')]


@app.command('init', epilog=examples(('doit shell init zsh', 'print the block, for `eval "$(doit shell init zsh)"` in your rc')))
def shell_init_command(shell: ShellArgument) -> None:
    """Print the startup block that nudges you about due items.

    Add `eval "$(doit shell init zsh)"` to your rc. It prints, so gate it on
    whatever switch decides you want reminders in this shell.
    """
    raise typer.Exit(emit(shell, 'init'))


@app.command(
    'completion', epilog=examples(('doit shell completion zsh', 'print the script, for `eval "$(doit shell completion zsh)"` in your rc'))
)
def completion_command(shell: ShellArgument) -> None:
    """Print the completion script for the verbs and your pursuit names.

    Source it from your fpath or rc: `eval "$(doit shell completion zsh)"`.
    """
    raise typer.Exit(emit(shell, 'completion'))
